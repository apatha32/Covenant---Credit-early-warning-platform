"""Phase 5 acceptance: every "Ask the filings" answer carries a valid citation.

Asks each question in evals/qa_questions.jsonl through the real /api/ask route (as anonymous
demo visitors, a fresh one every few questions because of the per-visitor limit), then checks:
  - an answer the model gives (answerable) has at least one citation;
  - every citation's quote is found word for word in a chunk of the cited filing, and that filing
    was public on the question's as-of date;
  - a refusal may still quote what the filings do say (e.g. "they only say X"), but every quote it
    gives is checked the same way.
Writes reports/qa_eval.md.

    QA_BASE_URL=http://localhost:3000 uv run python scripts/eval_qa.py   (DATABASE_URL: the demo DB)
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re

import httpx

from tripwire_common.db import connect
from tripwire_common.settings import REPO_ROOT, get_settings

QUESTIONS = REPO_ROOT / "evals" / "qa_questions.jsonl"
REPORT = REPO_ROOT / "reports" / "qa_eval.md"
PER_VISITOR = 3

_TRANS = str.maketrans({"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
                        "\u2011": "-", "\u2013": "-", "\u2014": "-"})  # fmt: skip


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.translate(_TRANS)).strip()


def anonymous_token(client: httpx.Client, url: str, anon_key: str) -> str:
    r = client.post(f"{url}/auth/v1/signup", headers={"apikey": anon_key}, json={})
    r.raise_for_status()
    return str(r.json()["access_token"])


def main() -> None:
    settings = get_settings()
    base = os.environ.get("QA_BASE_URL", "http://localhost:3000")
    url = settings.require("supabase_url")
    anon = settings.require("supabase_anon_key")
    questions = [json.loads(line) for line in QUESTIONS.read_text().splitlines() if line.strip()]
    rows = []
    with httpx.Client(timeout=120) as client, connect() as conn:
        token = ""
        for i, q in enumerate(questions):
            if i % PER_VISITOR == 0:
                token = anonymous_token(client, url, anon)
            payload = {"cik": q["cik"], "question": q["question"], "as_of": q["as_of"]}
            headers = {"Authorization": f"Bearer {token}"}
            r = client.post(f"{base}/api/ask", headers=headers, json=payload)
            body = r.json()
            problems = []
            if r.status_code != 200:
                problems.append(f"HTTP {r.status_code}: {body.get('error')}")
                citations = []
            else:
                citations = body.get("citations", [])
                if body.get("answerable") and not citations:
                    problems.append("answer without a citation")
            for c in citations:
                chunks = conn.execute(
                    """select chunk_text from curated.filing_chunk
                       where cik = %s and accession = %s and filed_date <= %s""",
                    [q["cik"], c["accession"], q["as_of"]],
                ).fetchall()
                if not chunks:
                    problems.append(f"cites {c['accession']}, not public on {q['as_of']}")
                elif not any(normalize(c["quote"]) in normalize(t[0]) for t in chunks):
                    problems.append(f"quote not found in {c['accession']}")
            rows.append({**q, "status": r.status_code, "answerable": body.get("answerable"),
                         "answer": body.get("answer", ""), "citations": len(citations),
                         "problems": problems})  # fmt: skip
            print(f"#{q['id']:>2} {'OK ' if not problems else 'BAD'} answerable="
                  f"{body.get('answerable')} citations={len(citations)} {problems}")  # fmt: skip
    REPORT.write_text(render(rows))
    print(f"report written: {REPORT}")


def render(rows: list[dict[str, object]]) -> str:
    answered = [r for r in rows if r["answerable"]]
    ok = [r for r in rows if not r["problems"]]
    lines = [
        "# Ask the filings: citation check",
        "",
        f"Generated by `scripts/eval_qa.py` on {dt.date.today()} against the live `/api/ask` "
        f"route: {len(rows)} questions from `evals/qa_questions.jsonl` about demo companies, "
        "including questions the filings cannot answer.",
        "",
        f"- **{len(ok)} of {len(rows)} passed.** {len(answered)} were answered and "
        f"{len(rows) - len(answered)} refused.",
        "- Pass means: an answer has at least one citation, every citation quote is found word for "
        "word in the cited filing (as stored), that filing was public on the question's as-of "
        "date. A refusal may quote what the filings do say; those quotes are checked the same way.",
        "",
        "| # | Company CIK | As of | Question | Result | Citations | Answer (start) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        problems = r["problems"] if isinstance(r["problems"], list) else []
        result = "pass" if not problems else "FAIL: " + "; ".join(str(p) for p in problems)
        kind = "answered" if r["answerable"] else "refused"
        answer = str(r["answer"]).replace("|", "/").replace("\n", " ")[:140]
        lines.append(f"| {r['id']} | {r['cik']} | {r['as_of']} | {r['question']} | "
                     f"{result} ({kind}) | {r['citations']} | {answer} |")  # fmt: skip
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
