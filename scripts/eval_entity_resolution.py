"""Write reports/entity_resolution_eval.md: matcher accuracy on the labeled borrower files.

Offline and deterministic (uses the committed universe fixture), so anyone can reproduce it:

    uv run python scripts/eval_entity_resolution.py
"""

from __future__ import annotations

from tripwire_common.config import load_entity_resolution_config
from tripwire_common.settings import REPO_ROOT
from tripwire_pipeline.entity.evaluate import evaluate, load_labeled, load_universe_fixture, render
from tripwire_pipeline.entity.matcher import Universe

FIXTURES = REPO_ROOT / "tests" / "entity" / "fixtures"
SETS = [
    ("holdout", "hold-out set (Phase 3 acceptance; never used for tuning)"),
    ("adversarial", "adversarial set (hand-written subsidiaries, namesakes, renamed companies)"),
    ("tune", "tuning set"),
]


def main() -> None:
    universe = Universe(load_universe_fixture(FIXTURES / "universe.csv.gz"),
                        load_entity_resolution_config())  # fmt: skip
    parts = [
        "# Entity resolution evaluation",
        "",
        "Generated by `scripts/eval_entity_resolution.py`. Universe: "
        f"{len(universe.companies)} SEC companies (current names, tickers, former names where "
        "known). Labeled files are in `tests/entity/fixtures/`; the 100-row files are generated "
        "by `scripts/make_er_fixtures.py` (typos, old names, missing / wrong / messy tickers, "
        "non-SEC companies).",
        "",
    ]
    for name, title in SETS:
        report = render(evaluate(universe, load_labeled(FIXTURES / f"borrowers_{name}.csv")), title)
        parts.append(report.replace("# Entity resolution:", "## Entity resolution:", 1)
                     .replace("\n## Wrong", "\n### Wrong"))  # fmt: skip
    out = REPO_ROOT / "reports" / "entity_resolution_eval.md"
    out.write_text("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
