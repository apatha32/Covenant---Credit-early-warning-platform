"""Choose the public demo portfolio and write <pack>/demo_portfolio.yaml (commit it).

Selection never looks at model scores, so the demo shows misses as well as hits:
  - the 25 largest companies (total assets just before filing) whose bankruptcy case started in
    the test window (after 2021-12-31) and that the model scored in it; plus Spirit, the demo story
  - 25 companies with no bankruptcy case ever: the largest in each SEC industry division, scored on
    every test-window quarter end

    uv run python scripts/build_demo_portfolio.py
"""

from __future__ import annotations

import datetime as dt

import polars as pl
import yaml

from tripwire_common.config import load_domain_pack
from tripwire_common.paths import training_root
from tripwire_common.sectors import sector_of

TEST_START = dt.date(2021, 12, 31)
SPIRIT = "0001498710"
N_BANKRUPT = 25
# Post-bankruptcy shells keep a new SEC name; a lender's book would list the name at filing.
NAME_AT_FILING = {"0000886158": "Bed Bath & Beyond Inc.", "0000768835": "Big Lots, Inc.",
                  "0001567892": "Mallinckrodt plc", "0000084129": "Rite Aid Corp.",
                  "0001498710": "Spirit Airlines, Inc.", "0001355096": "Qurate Retail, Inc.",
                  "0001592057": "Enviva Inc."}  # fmt: skip
HEALTHY_PER_SECTOR = {"Manufacturing": 6, "Services": 4, "Transportation & utilities": 4,
                      "Retail": 4, "Mining & energy": 3, "Wholesale": 2,
                      "Construction": 2}  # fmt: skip


def main() -> None:
    pack = load_domain_pack()
    root = training_root(pack.metrics.mapping_version)
    data = pl.read_parquet(root / "datasets" / "feature_set=v1" / "dataset.parquet",
                           columns=["cik", "as_of_date", "log_total_assets"])  # fmt: skip
    cases = pl.read_parquet(root / "labels" / "cases.parquet")
    companies = pl.read_parquet(root / "companies.parquet").select("cik", "name", "sic")
    test = data.filter(pl.col("as_of_date") >= TEST_START)

    recent = cases.filter(pl.col("case_start") > TEST_START).join(test, on="cik", how="semi")
    size_before = (
        recent.join(data, on="cik")
        .filter(pl.col("as_of_date") < pl.col("case_start"))
        .sort("as_of_date")
        .group_by("cik", "case_start")
        .agg(pl.col("log_total_assets").last())
    )
    first_case = (
        size_before.join(recent.select("cik", "case_start", "accession"), on=["cik", "case_start"])
        .sort("case_start")
        .group_by("cik")
        .agg(pl.col("case_start").first(), pl.col("accession").first(),
             pl.col("log_total_assets").max())
        # Co-registrants (parent + subsidiary on one 8-K) are one borrower: keep the larger.
        .sort("log_total_assets", descending=True, nulls_last=True)
        .unique(subset="accession", keep="first", maintain_order=True)
    )  # fmt: skip
    biggest = first_case.sort("log_total_assets", descending=True, nulls_last=True)
    chosen = biggest.head(N_BANKRUPT)
    if SPIRIT not in set(chosen["cik"]):
        chosen = pl.concat([chosen, biggest.filter(pl.col("cik") == SPIRIT)])

    n_dates = test["as_of_date"].n_unique()
    always_scored = (
        test.group_by("cik").agg(pl.len().alias("n"), pl.col("log_total_assets").last())
        .filter(pl.col("n") == n_dates)
        .join(cases, on="cik", how="anti")
        .join(companies, on="cik")
        .with_columns(sector=pl.col("sic").map_elements(sector_of, return_dtype=pl.String))
        .sort("log_total_assets", descending=True)
    )  # fmt: skip
    healthy = pl.concat(
        [always_scored.filter(pl.col("sector") == s).head(n) for s, n in HEALTHY_PER_SECTOR.items()]
    )

    rows = []
    for r in chosen.join(companies, on="cik").sort("case_start").iter_rows(named=True):
        name = NAME_AT_FILING.get(r["cik"], r["name"])
        rows.append({"cik": int(r["cik"]), "name": name, "group": "bankruptcy",
                     "case_start": r["case_start"].isoformat()})  # fmt: skip
    for r in healthy.iter_rows(named=True):
        rows.append({"cik": int(r["cik"]), "name": r["name"], "group": "healthy"})

    out = {
        "version": 1,
        "generated_on": dt.date.today().isoformat(),
        "criteria": __doc__.split("\n\n")[1].strip(),
        "tenant": "Demo Credit Fund (fictional)",
        "portfolio": "Demo watchlist",
        "story": {"cik": int(SPIRIT), "as_of": "2024-06-30"},
        "companies": rows,
    }
    path = pack.directory / "demo_portfolio.yaml"
    header = "# GENERATED by scripts/build_demo_portfolio.py. Public SEC data only.\n"
    path.write_text(header + yaml.safe_dump(out, sort_keys=False, width=100))
    print(f"{len(rows)} companies -> {path}")


if __name__ == "__main__":
    main()
