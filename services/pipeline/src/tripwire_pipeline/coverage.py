"""Metric coverage report: how well the mapping covers the companies we process."""

from __future__ import annotations

import datetime as dt

import psycopg
from psycopg import sql

from tripwire_common.config import MetricMapping

# Metrics a company needs for the core credit ratios (Altman Z components, liquidity, leverage).
CORE_METRICS = ["revenue", "operating_income", "net_income", "operating_cash_flow", "cash",
                "current_assets", "current_liabilities", "total_assets", "total_liabilities",
                "retained_earnings"]  # fmt: skip


def render_coverage(
    conn: psycopg.Connection, ciks: list[str], mapping: MetricMapping, as_of: dt.date
) -> str:
    version = mapping.mapping_version
    in_scope = [r[0] for r in conn.execute(
        "select cik from curated.company where cik = any(%s) and not is_excluded order by cik",
        [ciks],
    ).fetchall()]  # fmt: skip
    n = len(in_scope)
    lines = [
        "# Metric coverage",
        "",
        "Generated by `python -m tripwire_pipeline coverage`. Covers the dev sample's in-scope",
        f"(non-excluded) companies: **{n}** of {len(ciks)}. Mapping version {version}.",
        "",
        "## Per metric",
        "",
        "Companies: in-scope companies with at least one value. Quarters: share of fiscal "
        "quarters 2016-2024 with a value, averaged over those companies (for balance-sheet "
        "metrics the fiscal-year-end date counts as the Q4 value). Derived: share of quarterly "
        "rows computed from year-to-date values, or of balance-sheet rows computed by a "
        "formula. Restated: periods whose value changed between versions.",
        "",
        "| Metric | Kind | Companies | Quarters 2016-24 | Rows | Derived | Restated periods "
        "| Tags used (share of rows) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, spec in mapping.metrics.items():
        # Balance-sheet rows at a fiscal-year end are that year's Q4 value.
        quarterly = sql.SQL(
            "period_type in ('Q', 'FY')" if spec.kind == "instant" else "period_type = 'Q'"
        )
        stats = conn.execute(
            sql.SQL("""select count(distinct cik), count(*),
                      count(*) filter (where is_derived),
                      count(*) filter (where {quarterly})
               from curated.financial_metric
               where mapping_version = %s and canonical_metric = %s and cik = any(%s)""").format(
                quarterly=quarterly
            ),
            [version, name, in_scope],
        ).fetchone()
        assert stats is not None
        companies, rows, derived, q_rows = stats
        quarters = conn.execute(
            sql.SQL("""select coalesce(avg(nq) / 36.0, 0) from (
                 select cik, count(distinct period_end) nq from curated.financial_metric
                 where mapping_version = %s and canonical_metric = %s and cik = any(%s)
                   and {quarterly} and period_end between '2016-01-01' and '2024-12-31'
                 group by cik) t""").format(quarterly=quarterly),
            [version, name, in_scope],
        ).fetchone()
        restated = conn.execute(
            """select count(*) from (
                 select 1 from curated.financial_metric
                 where mapping_version = %s and canonical_metric = %s and cik = any(%s)
                 group by cik, period_type, period_end having count(distinct value) > 1) t""",
            [version, name, in_scope],
        ).fetchone()
        tags = conn.execute(
            """select source_tag, count(*) from curated.financial_metric
               where mapping_version = %s and canonical_metric = %s and cik = any(%s)
               group by 1 order by 2 desc""",
            [version, name, in_scope],
        ).fetchall()
        shares = [f"{t.replace('us-gaap:', '')} {c / rows:.0%}" for t, c in tags]
        tag_text = "<br>".join(shares) if rows else "-"
        q_share = f"{float(quarters[0]) if quarters else 0:.0%}"
        derived_share = f"{derived / q_rows:.0%}" if q_rows else "-"
        lines.append(
            f"| {name} | {spec.kind} | {companies}/{n} ({companies / n:.0%}) | {q_share} | {rows} "
            f"| {derived_share} | {restated[0] if restated else 0} | {tag_text} |"
        )

    recent_since = as_of - dt.timedelta(days=550)
    active = conn.execute(
        """select count(distinct cik) from curated.financial_metric
           where mapping_version = %s and cik = any(%s) and period_type = 'FY'
             and period_end >= %s and filed_date <= %s""",
        [version, in_scope, recent_since, as_of],
    ).fetchone()
    n_active = active[0] if active else 0
    complete = conn.execute(
        """with latest as (
             select distinct on (cik, canonical_metric) cik, canonical_metric
             from curated.financial_metric_as_of(%s, %s)
             where cik = any(%s) and period_type = 'FY' and canonical_metric = any(%s)
               and period_end >= %s
             order by cik, canonical_metric, period_end desc)
           select count(*) from (select cik from latest group by cik
                                 having count(*) = %s) t""",
        [as_of, version, in_scope, CORE_METRICS, recent_since, len(CORE_METRICS)],
    ).fetchone()  # fmt: skip
    quarantine = conn.execute(
        """select source, rule_violated, count(*) from staging.quarantine
           where source like 'pipeline_%%' group by 1, 2 order by 1, 3 desc"""
    ).fetchall()
    lines += [
        "",
        "## Core metric completeness",
        "",
        f"In-scope companies with every core metric ({', '.join(CORE_METRICS)}) for a fiscal year "
        f"ending in the 18 months before {as_of.isoformat()}, as known on that date: "
        f"**{complete[0] if complete else 0}** of the {n_active} companies that filed such a "
        f"fiscal year ({n} in scope in total).",
        "",
        "Gaps checked by hand (dev sample, 2026-10-21): the most common missing core metrics are "
        "operating_income (company reports no operating-income subtotal; some report only "
        "CostsAndExpenses) and revenue (pre-revenue companies, e.g. clinical-stage biotech).",
        "",
        "## Quarantine (pipeline)",
        "",
        "| Source | Rule | Records |",
        "|---|---|---|",
        *[f"| {s} | {r} | {c} |" for s, r, c in quarantine],
    ]
    return "\n".join(lines) + "\n"
