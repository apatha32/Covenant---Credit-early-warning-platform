"""Score text-signal predictions against the labelled eval set and render the report."""

from __future__ import annotations

import datetime as dt
from typing import Any

from tripwire_common.config import TextSignals


def score(
    passages: list[dict[str, Any]], predictions: list[dict[str, Any]], types: list[str]
) -> dict[str, dict[str, float | int]]:
    """Per signal type: true/false positives, false negatives, precision, recall. A prediction
    counts only if its evidence quote passed the check (rejected quotes are not predictions)."""
    by_id = {p["id"]: set(p["predicted"]) for p in predictions}
    out: dict[str, dict[str, float | int]] = {}
    for t in [*types, "all"]:
        tp = fp = fn = 0
        for p in passages:
            gold = set(p["labels"]) if t == "all" else {t} & set(p["labels"])
            pred = by_id.get(p["id"], set())
            pred = pred if t == "all" else {t} & pred
            tp += len(gold & pred)
            fp += len(pred - gold)
            fn += len(gold - pred)
        out[t] = {"tp": tp, "fp": fp, "fn": fn,
                  "precision": tp / (tp + fp) if tp + fp else float("nan"),
                  "recall": tp / (tp + fn) if tp + fn else float("nan")}  # fmt: skip
    return out


def _pct(x: float | int) -> str:
    return "n/a" if x != x else f"{x * 100:.0f}%"  # NaN check


def render(
    config: TextSignals, passages: list[dict[str, Any]], runs: list[dict[str, Any]], today: dt.date
) -> str:
    types = list(config.signals)
    positives = {t: sum(t in p["labels"] for p in passages) for t in types}
    scored = [(r, score(passages, r["predictions"], types)) for r in runs]
    names = [f"{r['prompt_version']} / {r['model']}" for r in runs]
    lines = [
        "# Text-signal eval",
        "",
        f"Generated by `python -m tripwire_llm eval` on {today}: {len(passages)} passages from "
        f"`evals/text_signals.jsonl` ({sum(bool(p['labels']) for p in passages)} with a signal), "
        f"one saved run per prompt version and model in `evals/results/`. Current prompt version: "
        f"`{config.prompt_version}`.",
        "",
        "A prediction counts only if its evidence quote is found word for word in the passage; "
        "quotes that fail that check are rejected and count as misses.",
        "",
        "## Precision / recall by signal type",
        "",
        "| Signal | Passages with it | " + " | ".join(names) + " |",
        "|---|---|" + "---|" * len(names),
    ]
    for t in [*types, "all"]:
        label = "**All signals**" if t == "all" else config.signals[t].label
        n = sum(positives.values()) if t == "all" else positives[t]
        cells = " | ".join(f"{_pct(s[t]['precision'])} / {_pct(s[t]['recall'])}" for _, s in scored)
        lines.append(f"| {label} | {n} | {cells} |")
    lines += [
        "",
        "## Cost (standard API prices)",
        "",
        "| Prompt / model | Input tokens | Output tokens | Rejected quotes | Cost of this eval |",
        "|---|---|---|---|---|",
    ]
    for (r, _), name in zip(scored, names, strict=True):
        lines.append(f"| {name} | {r['input_tokens']:,} | {r['output_tokens']:,} | "
                     f"{r['rejected_quotes']} | ${r['cost_usd']:.2f} |")  # fmt: skip
    lines += [
        "",
        "## Decision",
        "",
        "Haiku 5.5 extracts every signal type. Sonnet 5.5 is about 20x the price per token; "
        "running it over the demo filings (~42M input tokens) would cost ~$42 with the Batch API, "
        "against a $5 budget, so per-type upgrades (`config/models.yaml` "
        "`llm.extraction_overrides`) are left empty.",
        "",
        "Prompt v2 sharpened three definitions after reading v1's errors (doubt resolved in an "
        "earlier period is not going-concern doubt; a plan to refinance, or a completed "
        "refinancing, is not refinancing risk; 'no customer above 10%' is not concentration). It "
        "fixed four errors and introduced five (new liquidity false positives), so v1 is kept. "
        "The v2 definitions are in `evals/results/signals-v2_definitions.yaml`.",
        "",
        "## Caveats",
        "",
        "- Small counts: several types have only 2-10 positive passages, so one passage moves "
        "precision or recall by 10-50 points.",
        "- v2 was written after reading v1's errors on this same set (no held-out set yet), which "
        "favours v2; it still did not beat v1.",
        "- One run per prompt and model: repeated runs of the same prompt can differ by a passage "
        "or two.",
        "- Labels were written by Claude Opus 5.5 (the coding assistant that built this project) "
        "reading each passage against the definitions in `text_signals.yaml`; borderline calls "
        "carry a `note` in the eval file. They are not independent of Claude: treat small "
        "differences between models with caution.",
        "",
    ]
    return "\n".join(lines)
