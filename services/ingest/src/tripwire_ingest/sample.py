"""Dev sample selection (SPEC 3.11): random eligible filers plus the known bankruptcies.

The random part is drawn from today's SEC ticker map, so it only contains companies that are
still registered (survivorship bias). That is acceptable for a dev sample; the training universe
in Phase 4 comes from the bulk files, which include dead companies.
"""

from __future__ import annotations

import datetime as dt
import logging
import random
from pathlib import Path

import polars as pl
import psycopg
import yaml

from tripwire_common.config import DevSample, DomainPack, SampleCompany, SecSourceConfig
from tripwire_common.runs import RunLog
from tripwire_common.storage import Storage
from tripwire_ingest.company import upsert_from_submissions
from tripwire_ingest.http import HttpClient
from tripwire_ingest.landing import land_submissions
from tripwire_ingest.sec import cik10, fetch_submissions

log = logging.getLogger(__name__)

ANNUAL_REPORT_FORMS = ("10-K", "10-K405", "10-KT")
XBRL_HISTORY_BY = dt.date(2015, 12, 31)


def has_xbrl_history(filings: pl.DataFrame, by: dt.date = XBRL_HISTORY_BY) -> bool:
    """True if the company filed an XBRL annual report on or before `by`."""
    hits = filings.filter(
        pl.col("form").is_in(ANNUAL_REPORT_FORMS)
        & (pl.col("isXBRL") == 1)
        & (pl.col("filingDate") <= by.isoformat())
    )
    return hits.height > 0


def build_dev_sample(
    conn: psycopg.Connection,
    storage: Storage,
    client: HttpClient,
    config: SecSourceConfig,
    pack: DomainPack,
    tickers: pl.DataFrame,
    run: RunLog,
    *,
    n: int,
    seed: int,
) -> DevSample:
    known = {cik10(k.cik) for k in pack.known_bankruptcies.companies}
    candidates = sorted(set(tickers["cik"].to_list()) - known)
    random.Random(seed).shuffle(candidates)  # noqa: S311  # sampling, not crypto

    accepted: list[SampleCompany] = []
    for cik in candidates:
        if len(accepted) == n:
            break
        run.counts["screened"] += 1
        try:
            payload = fetch_submissions(client, config, cik)
            if payload is None:
                run.counts["rejected_not_found"] += 1
                continue
            _, company, filings = land_submissions(conn, storage, payload, run)
            upsert_from_submissions(conn, company, pack)
        except Exception as exc:  # one bad company must not stop sampling
            run.item_failed(cik, exc)
            continue
        sic = company["sic"][0]
        if pack.exclusions.exclusion_reason(int(sic) if sic else None):
            run.counts["rejected_excluded_sector"] += 1
        elif not has_xbrl_history(filings):
            run.counts["rejected_no_xbrl_history"] += 1
        else:
            accepted.append(SampleCompany(cik=int(cik), name=company["name"][0]))
    run.counts["accepted"] = len(accepted)
    if len(accepted) < n:
        raise RuntimeError(f"only {len(accepted)} of {n} eligible companies found")

    return DevSample(
        version=1,
        generated_on=dt.date.today().isoformat(),
        seed=seed,
        criteria=(
            f"Random draw (seed {seed}) from SEC company_tickers.json; SIC not excluded by the "
            f"domain pack; at least one XBRL annual report filed on or before "
            f"{XBRL_HISTORY_BY.isoformat()}. Plus every company in known_bankruptcies.yaml."
        ),
        random=sorted(accepted, key=lambda c: c.cik),
        known_bankruptcies=[
            SampleCompany(cik=k.cik, name=k.name) for k in pack.known_bankruptcies.companies
        ],
    )


def write_dev_sample(sample: DevSample, path: Path) -> None:
    header = (
        "# GENERATED by `python -m tripwire_ingest build-sample`. Commit it: it pins the dev\n"
        "# sample so every re-run ingests the same companies. Regenerate only on purpose.\n"
    )
    path.write_text(header + yaml.safe_dump(sample.model_dump(), sort_keys=False, width=100))
